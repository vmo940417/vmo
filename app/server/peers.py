def peers_for(code: str, sector_name: str | None) -> list[str]:
    """이 종목과 함께 볼 동종 종목 코드들을 고른다(자기 자신 제외, 최대 6개)."""
    theme = CODE_OVERRIDES.get(code)

    if theme is None and sector_name:
        cleaned = sector_name.replace(" ", "")
        theme = SECTOR_ALIASES.get(sector_name) or SECTOR_ALIASES.get(cleaned)
        if theme is None:
            for alias, key in SECTOR_ALIASES.items():
                if alias in sector_name or sector_name in alias:
                    theme = key
                    break

    if theme is None:
        # 종목이 어느 테마 목록에 들어 있으면 그 테마로 본다.
        for key, codes in PEERS.items():
            if code in codes:
                theme = key
                break

    if theme is None:
        return []
    return [c for c in PEERS.get(theme, []) if c != code][:6]


def theme_of(code: str, sector_name: str | None) -> str | None:
    """이 종목이 속한 테마 이름."""
    if code in CODE_OVERRIDES:
        return CODE_OVERRIDES[code]
    for key, codes in PEERS.items():
        if code in codes:
            return key
    if sector_name:
        return SECTOR_ALIASES.get(sector_name) or SECTOR_ALIASES.get(sector_name.replace(" ", ""))
    return None
